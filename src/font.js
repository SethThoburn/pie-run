const FONT_H = 7;
const glyphCache = new Map();

function fontGlyph(ch) {
  return FONT_SRC[ch] || FONT_SRC[ch.toUpperCase()] || FONT_SRC['?'];
}

// Width in pixels of a string drawn at `scale` (1px letter spacing).
function measureText(str, scale = 1) {
  let w = 0;
  for (const ch of str) w += (fontGlyph(ch)[0].length + 1) * scale;
  return Math.max(0, w - scale);
}

// Cached canvas for one glyph: fill colour, optional 1px outline colour.
function glyphCanvas(ch, scale, color, outline) {
  const key = ch + '|' + scale + '|' + color + '|' + (outline || '');
  let c = glyphCache.get(key);
  if (c) return c;
  const rows = fontGlyph(ch);
  const gw = rows[0].length;
  const o = outline ? 1 : 0;
  c = document.createElement('canvas');
  c.width = gw * scale + o * 2;
  c.height = FONT_H * scale + o * 2;
  const g = c.getContext('2d');
  const paint = (col, dx, dy) => {
    g.fillStyle = col;
    for (let y = 0; y < FONT_H; y++) {
      for (let x = 0; x < gw; x++) {
        if (rows[y][x] === '#') g.fillRect(o + dx + x * scale, o + dy + y * scale, scale, scale);
      }
    }
  };
  if (outline) {
    for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) if (dx || dy) paint(outline, dx, dy);
  }
  paint(color, 0, 0);
  glyphCache.set(key, c);
  return c;
}

// Draws text with its top-left at (x, y) unless align is 'center' or 'right'.
// Returns the drawn width.
function drawText(ctx, str, x, y, opts = {}) {
  const scale = opts.scale || 1;
  const color = opts.color || '#fff';
  const outline = opts.outline || null;
  const w = measureText(str, scale);
  let cx = Math.round(opts.align === 'center' ? x - w / 2 : opts.align === 'right' ? x - w : x);
  const cy = Math.round(y);
  const o = outline ? 1 : 0;
  for (const ch of str) {
    const gw = fontGlyph(ch)[0].length;
    if (ch !== ' ') ctx.drawImage(glyphCanvas(ch, scale, color, outline), cx - o, cy - o);
    cx += (gw + 1) * scale;
  }
  return w;
}
